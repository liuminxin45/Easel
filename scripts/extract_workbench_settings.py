"""Refresh the isolated settings implementation from the reviewed Easel web source.

Only settings helpers and schemas are copied. No web application, startup hook,
model transport, or business route is imported into the private profile.
"""
import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'web/app.py'
TARGET = ROOT / 'easel_workbench/runtime/settings_upstream.py'


def extract():
    source = SOURCE.read_text(encoding='utf-8')
    tree = ast.parse(source)
    definitions = {node.name: node for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))}
    selected = {'_model_channels', 'api_settings_models_save', 'api_models_available', 'api_models_selftest',
                'api_local_agents', 'api_local_agent_enable'}
    excluded = {'_harness_settings', '_read_env', '_write_env_direct', '_warn_http_transport_unavailable'}
    pending = list(selected)
    while pending:
        for node in ast.walk(definitions[pending.pop()]):
            if isinstance(node, ast.Name) and node.id in definitions and node.id not in selected | excluded:
                selected.add(node.id)
                pending.append(node.id)
    constants = {'_PLACEHOLDER_RE', '_ENV_VALUE_OK', '_SLOT_ENV_KEYS', '_FETCH_KEY_BY_SLOT',
                 'RESERVED_PROVIDER_KEYS', 'THINKING_FORMATS', 'THINKING_COMPAT_KEYS'}
    nodes = [node for node in tree.body if getattr(node, 'name', None) in selected or
             isinstance(node, (ast.Assign, ast.AnnAssign)) and any(
                 isinstance(target, ast.Name) and target.id in constants
                 for target in (node.targets if isinstance(node, ast.Assign) else [node.target]))]
    header = '''"""Settings-only projection of the reviewed upstream web implementation.
Generated by scripts/extract_workbench_settings.py; do not add private policy here.
Dependencies, roots and persistence are injected per SettingsService operation.
"""
import asyncio, ipaddress, json, os, re, shutil, socket, sys, time, urllib.error, urllib.parse, urllib.request
from pathlib import Path
from fastapi import HTTPException
from pydantic import BaseModel, Field, StrictBool
from easel.direct_api import DirectAPIError, api_config, read_settings
from easel.gateway_endpoint import chat_completions_url, port_source
from easel import harnesses
from easel.harnesses import store as harness_store
from easel.harnesses.base import HarnessError
'''
    parts = [header]
    lines = source.splitlines()
    for node in nodes:
        if hasattr(node, 'decorator_list'):
            node.decorator_list = []
        parts.append(ast.unparse(node))
    TARGET.write_text('\n\n'.join(parts) + '\n', encoding='utf-8')
    return {'source_sha256': hashlib.sha256(source.encode()).hexdigest(), 'definitions': sorted(selected),
            'sha256': hashlib.sha256(TARGET.read_bytes()).hexdigest()}


if __name__ == '__main__':
    import json
    print(json.dumps(extract()))
